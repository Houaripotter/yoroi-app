/** Ordre d'affichage : du plus simple au plus specialise */
const ORDRE = ['debutant-fullbody-3j', 'fullbody-2j', 'ppl-3j', 'ppl-6j', 'haut-bas-4j', 'split-5j', 'bas-du-corps-4j', 'fessiers-ventre-4j', 'pecs-priorite-4j', 'prise-de-masse-4j', 'perte-poids-4j', 'seche-4j', 'course-5km-8sem', 'course-10km-8sem', 'foot-prevention-2j', 'padel-raquette-2j', 'mobilite-3j', 'force-3j', 'combat-force-2j', 'grip-2j', 'cou-combat-2j', 'sac-debutant-3j', 'sac-cardio-3j', 'sac-mma-3j', 'sac-hiit-4sem', 'halteres-maison-3j', 'maison-3j'];
PROGRAMMES.sort((a, b) => (ORDRE.indexOf(a.id) + 100) % 100 - (ORDRE.indexOf(b.id) + 100) % 100);

export function programmeParId(id: string | null | undefined): Programme | undefined {
  if (!id) return undefined;
  return PROGRAMMES.find((p) => p.id === id);
}

export function libelleNiveau(n: Niveau): string {
  return n === 'debutant' ? 'Débutant' : n === 'intermediaire' ? 'Intermédiaire' : 'Confirmé';
}

export function libelleMateriel(m: Materiel): string {
  return m === 'maison' ? 'Sans matériel' : m === 'halteres' ? 'Haltères' : 'En salle';
}

/** Sport dont l'illustration accompagne le programme */
export function sportDuProgramme(p: Programme): string {
  if (p.sport) return p.sport;
  const rounds = p.jours.find((j) => j.rounds)?.rounds;
  if (rounds) return rounds.sport;
  if (p.objectif === 'combat') return 'mma';
  if (p.objectif === 'course') return 'running';
  if (p.materiel === 'maison') return 'street_workout';
  return 'musculation';
}

/** Series par groupe musculaire sur une semaine type (les jours tournent selon joursParSemaine) */
export function seriesParSemaine(p: Programme): Record<string, number> {
  const out: Record<string, number> = {};
  for (let i = 0; i < p.joursParSemaine; i++) {
    const j = p.jours[i % p.jours.length];
    for (const e of j.exos) out[e.muscle] = (out[e.muscle] ?? 0) + e.series;
  }
  return out;
}

/** « 2 min 30 », « 90 s » */
export function libelleRepos(sec: number): string {
  if (sec < 120) return `${sec} s`;
  const m = Math.floor(sec / 60);
  const s = sec % 60;
  return s ? `${m} min ${s}` : `${m} min`;
}
