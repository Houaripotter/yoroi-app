/** Choix dans l'ordre pour un sport, termines par l'icone de sa famille */
export function sportArtChoices(sport: string): string[] {
  const list = SPORT_ART_MAP[sport] ?? [];
  const icon = `@${CATEGORY_ICON[getSportCategory(sport)] ?? 'medaille'}`;
  return [...list, icon, '@medaille'];
}
