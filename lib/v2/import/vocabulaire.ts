export type ExoReconnu = { nom: string; sur: boolean };

let cles: string[] | null = null;
const clesTriees = (): string[] => (cles ??= Object.keys(VOCABULAIRE).sort((a, b) => b.length - a.length));

/** Reconnait le nom ecrit par la personne. `biblio` : les noms de la bibliotheque (et de son historique). */
export function reconnaitreExo(saisi: string, biblio: ExoCherchable[]): ExoReconnu {
  const p = ` ${plier(saisi)} `;
  if (p.trim() === '') return { nom: saisi, sur: false };
  // 1. le vocabulaire de salle : la plus longue expression contenue gagne
  for (const k of clesTriees()) {
    if (p.includes(` ${k} `)) return { nom: VOCABULAIRE[k], sur: true };
  }
  // 2. la recherche de l'app, en retirant les mots qu'elle ne connait pas
  const exact = biblio.find((e) => plier(e.name) === p.trim() || (e.autre && plier(e.autre) === p.trim()));
  if (exact) return { nom: exact.name, sur: true };
  const mots = motsRecherche(saisi);
  const utiles = mots.filter((w) => biblio.some((e) => scoreExo(e, w) > 0));
  if (utiles.length >= 2 && utiles.length >= Math.ceil(mots.length * 0.6)) {
    const top = chercherExos(biblio, utiles.join(' '))[0];
    if (top) return { nom: top.name, sur: true };
  }
  return { nom: saisi, sur: false };
}
